export const LANGUAGES = { en: 'English', es: 'Español' };

export function translator(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  return (key, vars = {}) =>
    (table[key] ?? STRINGS.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

